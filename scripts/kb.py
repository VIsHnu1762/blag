def collect(extra: dict[Path, str]) -> list[tuple[Path, dict, str]]:
    """Every page with its frontmatter, using freshly generated content where available."""
    result = []
    paths = set(pages()) | {p for p in extra if p.suffix == ".md" and EXPORT not in p.parents}
    tmp = sorted(paths, key=lambda p: order_key(p, extra.get(p)))
    for p in tmp:
        text = extra.get(p) or p.read_text(encoding="utf-8")
        meta, body = split_frontmatter(text)
        result.append((p, meta or {}, body))
    return result


def gen_indexes(all_pages: list[tuple[Path, dict, str]]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    index = [{"id": m.get("id"), "title": m.get("title"), "section": m.get("section"), "status": m.get("status"),
              "summary": m.get("summary"), "last_updated": str(m.get("last_updated")), "related": m.get("related", []),
              "audience": m.get("audience", []), "path": str(p.relative_to(ROOT))} for p, m, _ in all_pages]
    out[EXPORT / "kb-index.json"] = json.dumps({"generated_by": "scripts/kb.py", "repo": REPO_URL, "pages": index}, indent=2, ensure_ascii=False) + "\n"

    # llms.txt
    lines = ["# BLAG: Are You Bluffing?", "",
             "> BLAG is a privacy-first social game for close friend groups of 3-8. Each day one friend makes a claim about their own habits "
             "(screen time, steps, late-night use) that may be a bluff; the others read it as TRUE or BLUFF, the sealed real number is revealed, "
             "and points reward reading friends well, never having 'good' habits. Daily points build into a monthly season with a finale. "
             "Pre-development: this repository is the knowledge base.", "",
             "Agents: read AGENTS.md first. The single-file export is kb/export/blag-kb.md. Data registers are YAML in kb/data/.", ""]
    section = None
    for p, m, _ in all_pages:
        sec = m.get("section", "")
        if sec != section:
            section = sec
            lines += ["", f"## {sec}"]
        lines.append(f"- [{m.get('title')}]({REPO_URL}/blob/main/{p.relative_to(ROOT)}): {m.get('summary', '')}")
    lines += ["", "## Optional", f"- [Single-file export]({REPO_URL}/blob/main/kb/export/blag-kb.md): the whole KB in one file",
              f"- [Page index (JSON)]({REPO_URL}/blob/main/kb/export/kb-index.json): ids, summaries and relations of every page"]
    out[ROOT / "llms.txt"] = "\n".join(lines) + "\n"

    # single-file bundle
    parts = ["# BLAG knowledge base (single-file export)\n",
             f"Generated by `scripts/kb.py` from {REPO_URL}. Do not edit. Links point to the files on GitHub.\n",
             "Read order follows the folders: 00 start here → 01 idea → … → 13 pitch → registers.\n"]
    for p, m, body in all_pages:
        rel = p.relative_to(ROOT)
        body = re.sub(r"^(#{1,5}) ", lambda mm: "#" + mm.group(1) + " ", body, flags=re.M)
        body = re.sub(r"\]\((?!https?:|mailto:|#)([^)\s]+)\)",
                      lambda mm: f"]({REPO_URL}/blob/main/{(p.parent / mm.group(1).split('#')[0]).resolve().relative_to(ROOT)}"
                                 + ("#" + mm.group(1).split('#', 1)[1] if '#' in mm.group(1) else "") + ")", body)
        parts.append(f"\n---\n\n<!-- page: {rel} · id: {m.get('id')} · status: {m.get('status')} · updated: {m.get('last_updated')} -->\n"
                     + body.replace(GENERATED_NOTE.split('{')[0], "<!-- "))
    out[EXPORT / "blag-kb.md"] = "\n".join(parts)
    return out


NAV_BEGIN, NAV_END = "# BEGIN NAV (generated by scripts/kb.py)", "# END NAV"


def gen_nav(all_pages: list[tuple[Path, dict, str]]) -> dict[Path, str]:
    """Write the site navigation into mkdocs.yml in KB reading order."""
    mk = ROOT / "mkdocs.yml"
    if not mk.exists():
        return {}
    lines = [NAV_BEGIN, "nav:"]
    open_dirs: list[str] = []
    for p, m, _ in all_pages:
        rel = p.relative_to(KB)
        dirs = list(rel.parts[:-1])
        while open_dirs and open_dirs != dirs[:len(open_dirs)]:
            open_dirs.pop()
        for d in dirs[len(open_dirs):]:
            open_dirs.append(d)
            readme = KB.joinpath(*open_dirs, "README.md")
            title = (split_frontmatter(readme.read_text(encoding="utf-8"))[0] or {}).get("title", d) if readme.exists() else d
            lines.append("  " * len(open_dirs) + f"- {json.dumps(title)}:")
        indent = "  " * (len(open_dirs) + 1)
        lines.append(f"{indent}- {json.dumps(m.get('title', rel.stem))}: {rel.as_posix()}")
    lines.append(NAV_END)
    text = mk.read_text(encoding="utf-8")
    if NAV_BEGIN in text:
        text = text[:text.index(NAV_BEGIN)] + "\n".join(lines) + text[text.index(NAV_END) + len(NAV_END):]
    else:
        text = text.rstrip() + "\n\n" + "\n".join(lines) + "\n"
    return {mk: text}


def build_all() -> dict[Path, str]:
    regs = gen_registers()
    all_pages = collect(regs)
    return {**regs, **gen_indexes(all_pages), **gen_nav(all_pages)}


# ---------------------------------------------------------------- checks
def check(generated: dict[Path, str]) -> list[str]:
    errors: list[str] = []
    known_ids: set[str] = set()
    for name, keys in [("ideas", ["items"]), ("decisions", ["items"]), ("questions", ["items"]),
                       ("risks", ["assumptions", "risks"]), ("sources", ["items"]), ("features", ["items"]), ("stats", ["items"])]:
        data = load(name)
        for k in keys:
            ids = [x["id"] for x in data[k]]
            dupes = {i for i in ids if ids.count(i) > 1}
            if dupes:
                errors.append(f"kb/data/{name}.yaml: duplicate ids {sorted(dupes)}")
            known_ids |= set(ids)
    known_ids |= {re.match(r"(ADR-\d{3})", p.name).group(1) for p in (KB / "07-architecture" / "adr").glob("ADR-*.md")}

    for x in load("questions")["items"]:
        if x.get("decided_by") and x["decided_by"] not in known_ids:
            errors.append(f"questions.yaml {x['id']}: decided_by {x['decided_by']} not found")
    for x in load("features")["items"]:
        for i in x["ideas"]:
            if i not in known_ids:
                errors.append(f"features.yaml {x['id']}: idea {i} not found")

    page_ids: dict[str, Path] = {}
    all_pages = collect(generated)
    for p, meta, body in all_pages:
        rel = p.relative_to(ROOT)
        if not meta:
            errors.append(f"{rel}: missing frontmatter")
            continue
        for k in REQUIRED:
            if k not in meta:
                errors.append(f"{rel}: frontmatter missing '{k}'")
        if meta.get("status") not in STATUSES:
            errors.append(f"{rel}: status '{meta.get('status')}' not in {sorted(STATUSES)}")
        pid = meta.get("id")
        if pid in page_ids:
            errors.append(f"{rel}: duplicate page id '{pid}' (also {page_ids[pid].relative_to(ROOT)})")
        page_ids[pid] = p
    for p, meta, body in all_pages:
        rel = p.relative_to(ROOT)
        for r in meta.get("related", []) or []:
            if r not in page_ids:
                errors.append(f"{rel}: related id '{r}' not found")
        text = body
        for m in re.finditer(r"\]\(([^)\s]+)\)", text):
            target = m.group(1).split("#")[0]
            if not target or re.match(r"^[a-z]+:", target):
                continue
            if not (p.parent / target).resolve().exists() and (p.parent / target).resolve() not in generated:
                errors.append(f"{rel}: broken link -> {m.group(1)}")
        for ref in set(ID_PATTERN.findall(text)):
            if ref not in known_ids:
                errors.append(f"{rel}: unknown id {ref}")

    for path, content in generated.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            errors.append(f"{path.relative_to(ROOT)}: out of date, run `python scripts/kb.py build`")
    return errors


def main() -> int:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    generated = build_all()
    if cmd == "build":
        for path, content in generated.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        generated = build_all()  # second pass so the bundle includes freshly written pages
        for path, content in generated.items():
            path.write_text(content, encoding="utf-8")
        print(f"built {len(generated)} files")
        cmd = "check"
    if cmd == "check":
        errors = check(generated)
        for e in errors:
            print("ERROR", e)
        print(f"{len(collect(generated))} pages checked, {len(errors)} problems")
        return 1 if errors else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
